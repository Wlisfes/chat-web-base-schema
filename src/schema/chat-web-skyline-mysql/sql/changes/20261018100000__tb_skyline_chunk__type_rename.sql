-- 枚举命名规则调整：模块 CHUNK_SYSTEM 更名为 CHUNK_SKYLINE；类型编码改为 CHUNK_<服务>_<业务表>_<业务字段>（业务表省略 tb_<服务>_ 前缀），系统通用枚举为 CHUNK_SKYLINE_COMMON_<业务字段>。
-- 类型映射：CHUNK_SYSTEM_ACCOUNT_USER_POST → CHUNK_SKYLINE_USER_POST；CHUNK_SYSTEM_ACCOUNT_USER_LEVEL → CHUNK_SKYLINE_USER_LEVEL；CHUNK_CRM_CRM_USER_SOURCE → CHUNK_CRM_USER_SOURCE；CHUNK_SYSTEM_COMMON_CONTACT_TYPE → CHUNK_SKYLINE_COMMON_CONTACT_TYPE。
-- 同步主子表 module 默认值与字段注释、type 字段注释；枚举项主键不变，业务表中引用的枚举项主键无需调整；重复执行不产生变化。
-- 回滚：UPDATE `tb_skyline_chunk_module` / `tb_skyline_chunk` SET `module` = IF(`module` = 'CHUNK_SKYLINE', 'CHUNK_SYSTEM', `module`), `type` = CASE `type` WHEN 'CHUNK_SKYLINE_USER_POST' THEN 'CHUNK_SYSTEM_ACCOUNT_USER_POST' WHEN 'CHUNK_SKYLINE_USER_LEVEL' THEN 'CHUNK_SYSTEM_ACCOUNT_USER_LEVEL' WHEN 'CHUNK_CRM_USER_SOURCE' THEN 'CHUNK_CRM_CRM_USER_SOURCE' WHEN 'CHUNK_SKYLINE_COMMON_CONTACT_TYPE' THEN 'CHUNK_SYSTEM_COMMON_CONTACT_TYPE' ELSE `type` END; 并恢复字段默认值与注释。

ALTER TABLE `tb_skyline_chunk_module`
    MODIFY COLUMN `module` varchar(32) NOT NULL DEFAULT 'CHUNK_SKYLINE' COMMENT '枚举所属模块：CHUNK_SKYLINE=SKYLINE（系统管理模块使用的枚举项）；CHUNK_CRM=CRM（CRM 客户关系管理模块使用的枚举项）；CHUNK_SRM=SRM（SRM 供应商关系管理模块使用的枚举项）',
    MODIFY COLUMN `type` varchar(128) NOT NULL COMMENT '枚举类型编码：CHUNK_SKYLINE_USER_POST=用户岗位（Skyline 账号岗位，仅一级枚举项，适用于普通下拉选择）；CHUNK_SKYLINE_USER_LEVEL=用户职级（Skyline 账号职级，P1-P8 专业序列、M1-M8 管理序列，仅一级枚举项）；CHUNK_SKYLINE_COMMON_CONTACT_TYPE=联系方式（系统通用联系方式类型，仅一级枚举项）；CHUNK_CRM_USER_SOURCE=客户注册来源（CRM 客户注册来源，仅一级枚举项）';

ALTER TABLE `tb_skyline_chunk`
    MODIFY COLUMN `module` varchar(32) NOT NULL DEFAULT 'CHUNK_SKYLINE' COMMENT '枚举所属模块：CHUNK_SKYLINE=SKYLINE；CHUNK_CRM=CRM；CHUNK_SRM=SRM',
    MODIFY COLUMN `type` varchar(128) NOT NULL COMMENT '枚举类型编码：CHUNK_SKYLINE_USER_POST=用户岗位（Skyline 账号岗位，仅一级枚举项，适用于普通下拉选择）；CHUNK_SKYLINE_USER_LEVEL=用户职级（Skyline 账号职级，P1-P8 专业序列、M1-M8 管理序列，仅一级枚举项）；CHUNK_SKYLINE_COMMON_CONTACT_TYPE=联系方式（系统通用联系方式类型，仅一级枚举项）；CHUNK_CRM_USER_SOURCE=客户注册来源（CRM 客户注册来源，仅一级枚举项）';

UPDATE `tb_skyline_chunk_module`
SET `module` = IF(`module` = 'CHUNK_SYSTEM', 'CHUNK_SKYLINE', `module`),
    `type` = CASE `type`
        WHEN 'CHUNK_SYSTEM_ACCOUNT_USER_POST' THEN 'CHUNK_SKYLINE_USER_POST'
        WHEN 'CHUNK_SYSTEM_ACCOUNT_USER_LEVEL' THEN 'CHUNK_SKYLINE_USER_LEVEL'
        WHEN 'CHUNK_CRM_CRM_USER_SOURCE' THEN 'CHUNK_CRM_USER_SOURCE'
        WHEN 'CHUNK_SYSTEM_COMMON_CONTACT_TYPE' THEN 'CHUNK_SKYLINE_COMMON_CONTACT_TYPE'
        ELSE `type`
    END
WHERE `module` = 'CHUNK_SYSTEM' OR `type` IN ('CHUNK_SYSTEM_ACCOUNT_USER_POST', 'CHUNK_SYSTEM_ACCOUNT_USER_LEVEL', 'CHUNK_CRM_CRM_USER_SOURCE', 'CHUNK_SYSTEM_COMMON_CONTACT_TYPE');

UPDATE `tb_skyline_chunk`
SET `module` = IF(`module` = 'CHUNK_SYSTEM', 'CHUNK_SKYLINE', `module`),
    `type` = CASE `type`
        WHEN 'CHUNK_SYSTEM_ACCOUNT_USER_POST' THEN 'CHUNK_SKYLINE_USER_POST'
        WHEN 'CHUNK_SYSTEM_ACCOUNT_USER_LEVEL' THEN 'CHUNK_SKYLINE_USER_LEVEL'
        WHEN 'CHUNK_CRM_CRM_USER_SOURCE' THEN 'CHUNK_CRM_USER_SOURCE'
        WHEN 'CHUNK_SYSTEM_COMMON_CONTACT_TYPE' THEN 'CHUNK_SKYLINE_COMMON_CONTACT_TYPE'
        ELSE `type`
    END
WHERE `module` = 'CHUNK_SYSTEM' OR `type` IN ('CHUNK_SYSTEM_ACCOUNT_USER_POST', 'CHUNK_SYSTEM_ACCOUNT_USER_LEVEL', 'CHUNK_CRM_CRM_USER_SOURCE', 'CHUNK_SYSTEM_COMMON_CONTACT_TYPE');
