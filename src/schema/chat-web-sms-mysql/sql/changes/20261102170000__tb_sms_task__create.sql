-- 新建 SMS 短信任务表：一批发送的客户、应用、内容模板和进度。号码不存在任务行，展开后写入 tb_sms_message。
-- 回滚：DROP TABLE IF EXISTS `tb_sms_task`;

CREATE TABLE IF NOT EXISTS `tb_sms_task` (
    `key_id` int NOT NULL AUTO_INCREMENT COMMENT '表主键',
    `task_name` varchar(128) NOT NULL COMMENT '任务名称',
    `user_key_id` int NOT NULL COMMENT 'CRM 客户主键',
    `user_name` varchar(128) NOT NULL COMMENT '客户名称快照',
    `user_alias` varchar(64) NULL COMMENT '客户别名快照',
    `app_key_id` int NOT NULL COMMENT 'SMS 短信应用主键',
    `app_id` varchar(32) NOT NULL COMMENT '应用ID快照',
    `app_alias` varchar(64) NOT NULL COMMENT '应用别名快照',
    `type` varchar(32) NOT NULL COMMENT '短信应用类型：MRKT=营销短信（用于营销推广内容）；NTFY=通知短信（用于业务通知内容）；SOTP=验证码（用于一次性验证码）',
    `content` varchar(1000) NULL COMMENT '短信内容模板：展开号码时复制到发送记录；每条内容不同时为空',
    `template_id` varchar(64) NULL COMMENT '短信模板ID快照',
    `currency` varchar(16) NOT NULL COMMENT '报价币种：售价和任务金额使用该币种，同一任务不得跨币种',
    `plan_time` datetime(3) NULL COMMENT '计划发送时间：为空表示立即发送',
    `start_time` datetime(3) NULL COMMENT '实际开始时间',
    `end_time` datetime(3) NULL COMMENT '实际结束时间',
    `status` varchar(32) NOT NULL DEFAULT 'pending' COMMENT '短信任务状态：pending=待发送（等待计划时间或入队）；sending=发送中（发送记录正在提交）；completed=已完成（成功、失败和取消条数已等于任务发送总数）；failed=失败（文件解析失败或应用禁用等任务级失败）；cancelled=已取消（人工取消，未发出的记录改为取消）',
    `source` varchar(32) NOT NULL COMMENT '短信任务来源：web=WEB（客户在网页创建）；api=API（调用提交接口创建）',
    `file_key` varchar(128) NULL COMMENT '号码文件对象键：号码不存任务行，文件展开后写入发送记录',
    `file_name` varchar(255) NULL COMMENT '号码文件名',
    `total_count` int NOT NULL DEFAULT 0 COMMENT '任务发送总数',
    `success_count` int NOT NULL DEFAULT 0 COMMENT '已成功条数：含发送成功和已送达',
    `fail_count` int NOT NULL DEFAULT 0 COMMENT '已失败条数：含提交失败和发送失败',
    `cancel_count` int NOT NULL DEFAULT 0 COMMENT '已取消条数：任务取消且尚未提交到通道',
    `charge_count` int NOT NULL DEFAULT 0 COMMENT '计费条数合计：各发送记录 segments 之和',
    `amount` bigint NOT NULL DEFAULT 0 COMMENT '客户售价合计：报价币种金额，放大百万倍存储，等于各发送记录 price 之和',
    `remark` varchar(1024) NULL COMMENT '备注',
    `create_by` varchar(19) NOT NULL COMMENT '创建账号UID',
    `modify_by` varchar(19) NULL COMMENT '更新账号UID',
    `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    `modify_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (`key_id`),
    KEY `idx_tb_sms_task_user_create_time` (`user_key_id`, `create_time`),
    KEY `idx_tb_sms_task_app_create_time` (`app_key_id`, `create_time`),
    KEY `idx_tb_sms_task_status_plan_time` (`status`, `plan_time`),
    KEY `idx_tb_sms_task_create_by` (`create_by`)
) ENGINE = InnoDB AUTO_INCREMENT = 1002001 DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_unicode_ci COMMENT = 'SMS 短信任务表';
