-- 新建 SMS 短信发送记录表：一条号码一条记录。msg_id 与 SRM 设备短信表相同，供应商成本、端口和路由不在本表。
-- 回滚：DROP TABLE IF EXISTS `tb_sms_message`;

CREATE TABLE IF NOT EXISTS `tb_sms_message` (
    `key_id` int NOT NULL AUTO_INCREMENT COMMENT '表主键',
    `msg_id` varchar(36) NOT NULL COMMENT '短信ID：提交时生成的雪花ID，重投保持不变',
    `task_key_id` int NULL COMMENT '短信任务主键：单条提交不挂任务时为空',
    `task_name` varchar(128) NULL COMMENT '短信任务名称快照',
    `user_key_id` int NOT NULL COMMENT 'CRM 客户主键',
    `user_name` varchar(128) NOT NULL COMMENT '客户名称快照',
    `user_alias` varchar(64) NULL COMMENT '客户别名快照',
    `app_key_id` int NOT NULL COMMENT 'SMS 短信应用主键',
    `app_id` varchar(32) NOT NULL COMMENT '应用ID快照',
    `app_alias` varchar(64) NOT NULL COMMENT '应用别名快照',
    `type` varchar(32) NOT NULL COMMENT '短信应用类型：MRKT=营销短信（用于营销推广内容）；NTFY=通知短信（用于业务通知内容）；SOTP=验证码（用于一次性验证码）',
    `template_id` varchar(64) NULL COMMENT '短信模板ID快照',
    `country_key_id` int NOT NULL COMMENT 'Finance 国家/地区主键',
    `mcc` varchar(4) NOT NULL COMMENT '移动国家代码',
    `to_number` varchar(32) NOT NULL COMMENT '接收号码：含国际区号，不带 + 号',
    `content` varchar(1000) NOT NULL COMMENT '实际发送内容',
    `encoding` varchar(16) NOT NULL COMMENT '编码方式：GSM7=GSM7（纯英文、数字和常用符号）；UCS2=UCS2（包含中文、emoji 等非 GSM7 字符）',
    `content_length` int NOT NULL COMMENT '内容字符数：短信内容按编码计算的字符数',
    `segments` int NOT NULL COMMENT '计费条数：GSM7 单条160/每段153，UCS2 单条70/每段67',
    `currency` varchar(16) NOT NULL COMMENT '报价币种：与所属任务一致；单条提交取生效报价币种',
    `price` bigint NOT NULL COMMENT '客户售价：报价币种金额，放大百万倍存储，等于生效报价 down_local 乘以计费条数',
    `submit_time` datetime(3) NOT NULL COMMENT '提交时间',
    `send_status` varchar(32) NOT NULL DEFAULT 'pending' COMMENT '短信发送状态：pending=待提交（已落库，尚未进入提交队列）；queued=已入队（已进入提交队列）；submitted=提交成功（短信已提交到设备，等待设备发送）；rejected=提交失败（短信未能提交到设备）；success=发送成功（设备已发出短信，等待送达回执）；failed=发送失败（设备发送短信失败）；delivered=已送达（短信已送达接收号码）；cancelled=已取消（任务取消且尚未提交到通道）',
    `send_time` datetime(3) NULL COMMENT '发送状态时间：发送状态变更时同步更新',
    `status_code` varchar(32) NULL COMMENT '状态码：通道或设备返回的发送状态码',
    `status_message` varchar(512) NULL COMMENT '状态说明：通道或设备返回的状态描述',
    `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    `modify_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (`key_id`),
    UNIQUE KEY `uk_tb_sms_message_msg_id` (`msg_id`),
    KEY `idx_tb_sms_message_task_create_time` (`task_key_id`, `create_time`),
    KEY `idx_tb_sms_message_user_create_time` (`user_key_id`, `create_time`),
    KEY `idx_tb_sms_message_app_create_time` (`app_key_id`, `create_time`),
    KEY `idx_tb_sms_message_status_create_time` (`send_status`, `create_time`),
    KEY `idx_tb_sms_message_to_number_create_time` (`to_number`, `create_time`),
    KEY `idx_tb_sms_message_create_time` (`create_time`)
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_unicode_ci COMMENT = 'SMS 短信发送记录表';
