CREATE TABLE IF NOT EXISTS `tb_srm_simbank_message` (
    `key_id` int NOT NULL AUTO_INCREMENT COMMENT '表主键',
    `source` varchar(32) NOT NULL COMMENT '上下行：down=下行（设备发出的短信）；up=上行（设备接收的短信）',
    `type` varchar(32) NULL COMMENT '短信类型：MRKT=营销短信（用于营销推广内容）；NTFY=通知短信（用于业务通知内容）；SOTP=验证码（用于一次性验证码）',
    `from_number` varchar(32) NOT NULL COMMENT '发送号码',
    `to_number` varchar(32) NOT NULL COMMENT '接收号码',
    `content` text NOT NULL COMMENT '短信内容',
    `segments` int NOT NULL DEFAULT 1 COMMENT '计费条数：长短信按拆分后的条数计费',
    `country_key_id` int NULL COMMENT '国家/地区：Finance 国家/地区主键，对方号码所在国家/地区',
    `mcc` varchar(4) NULL COMMENT 'MCC快照：对方号码所在国家/地区的移动国家代码',
    `send_status` varchar(32) NULL COMMENT '发送状态：delivered=已送达（短信已送达接收号码）；submitted=提交成功（短信已提交到设备，等待最终发送结果）；undelivered=未送达（短信未能送达接收号码）；unknown=未知（未获取到明确的送达结果）',
    `send_time` datetime(3) NULL COMMENT '发送状态时间：发送状态变更时同步更新',
    `status_code` varchar(32) NULL COMMENT '状态码：设备返回的发送状态码',
    `status_message` varchar(512) NULL COMMENT '状态说明：设备返回的状态描述',
    `channel_key_id` int NULL COMMENT '通道ID：发送时使用的通道主键',
    `channel_name` varchar(64) NULL COMMENT '通道名称快照',
    `simbank_key_id` int NOT NULL COMMENT '设备ID：SRM SIMBANK 设备主键',
    `simbank_name` varchar(64) NOT NULL COMMENT '设备名称快照',
    `user_key_id` int NOT NULL COMMENT '归属供应商ID：SRM 供应商主键',
    `user_name` varchar(64) NOT NULL COMMENT '归属供应商名称快照',
    `user_alias` varchar(64) NULL COMMENT '归属供应商别名快照',
    `owner_user_uid` varchar(19) NOT NULL COMMENT '归属人账号UID快照',
    `port_key_id` int NOT NULL COMMENT '端口ID：SRM SIMBANK 端口主键',
    `port` int NOT NULL COMMENT '端口编号快照',
    `sim` varchar(32) NULL COMMENT 'SIM 卡号码快照：发送时端口 SIM 卡号码',
    `iccid` varchar(22) NULL COMMENT 'ICCID快照：发送时端口 SIM 卡唯一编号',
    `cost` bigint NOT NULL DEFAULT 0 COMMENT '供应商成本：USD总额（放大百万倍存储）',
    `price` bigint NOT NULL DEFAULT 0 COMMENT '客户售价：USD总额（放大百万倍存储）',
    `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    `modify_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (`key_id`),
    KEY `idx_tb_srm_simbank_message_channel_create_time` (`channel_key_id`, `create_time`),
    KEY `idx_tb_srm_simbank_message_simbank_create_time` (`simbank_key_id`, `create_time`),
    KEY `idx_tb_srm_simbank_message_port_create_time` (`port_key_id`, `create_time`),
    KEY `idx_tb_srm_simbank_message_user_create_time` (`user_key_id`, `create_time`),
    KEY `idx_tb_srm_simbank_message_to_number` (`to_number`),
    KEY `idx_tb_srm_simbank_message_create_time` (`create_time`)
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_unicode_ci COMMENT = 'SRM SIMBANK 短信历史表';
